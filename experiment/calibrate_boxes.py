"""
Calibrate the DocTags loc → pixel mapping using a GROUND-TRUTH training sample.

The training labels' <loc> coords were generated by docling's formula
(loc = 500 * coord / page_dim) relative to the image stored in the parquet, so
per-axis mapping (coord = loc/500 * W) SHOULD reproduce the boxes exactly. Render
all 3 schemes on a real sample → whichever aligns is the correct one.

Usage:
    python calibrate_boxes.py --row 0
Env/flags: HF_TOKEN (for the private dataset), --repo, --file (parquet shard).
Outputs: box_<scheme>.png for each scheme + prints image size and loc ranges.
"""
from __future__ import annotations

import argparse
import io
import os
import re

import pandas as pd
from PIL import Image, ImageDraw

_BOX_RE = re.compile(r"<([a-z_0-9]+)><loc_(\d+)><loc_(\d+)><loc_(\d+)><loc_(\d+)>")
_COLORS = {"section_header": (220, 40, 40), "title": (220, 40, 40),
           "text": (40, 110, 215), "list_item": (40, 160, 60),
           "caption": (210, 130, 20), "picture": (160, 40, 200),
           "table": (20, 170, 170), "page_footer": (130, 130, 130),
           "page_header": (130, 130, 130)}

def _color(tag):
    for k, c in _COLORS.items():
        if tag.startswith(k):
            return c
    return (90, 90, 90)

def _decode(field):
    b = field.get("bytes") if isinstance(field, dict) else field
    return Image.open(io.BytesIO(b)).convert("RGB")

def _map(lx, ly, W, H, scheme):
    if scheme == "per-axis":
        return lx / 500 * W, ly / 500 * H
    S = max(W, H)
    if scheme == "square-topleft":
        return lx / 500 * S, ly / 500 * S
    return lx / 500 * S - (S - W) / 2, ly / 500 * S - (S - H) / 2

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default="nbdaaa/all-ocr-data")
    ap.add_argument("--file", default="data/train-00000-of-00064.parquet")
    ap.add_argument("--row", type=int, default=0)
    # Per-axis grids derived from ground-truth analysis (NOT 500). Tune these so
    # boxes align, then lock the values that work across several rows.
    ap.add_argument("--grid-x", type=float, default=345.0)
    ap.add_argument("--grid-y", type=float, default=293.0)
    args = ap.parse_args()

    from huggingface_hub import hf_hub_download
    p = hf_hub_download(args.repo, args.file, repo_type="dataset",
                        token=os.environ.get("HF_TOKEN"))
    df = pd.read_parquet(p)
    row = df.iloc[args.row]
    img = _decode(row["image"])
    doctags = row["output_text"]
    W, H = img.size

    elems = list(_BOX_RE.finditer(doctags))
    xs_all = [int(v) for m in elems for v in m.groups()[1:]]
    # split x vs y to see their ranges separately (key for per-axis vs square)
    xvals = [int(m.group(2)) for m in elems] + [int(m.group(4)) for m in elems]
    yvals = [int(m.group(3)) for m in elems] + [int(m.group(5)) for m in elems]
    print(f"image {W}x{H}px · {len(elems)} elems")
    print(f"  loc X range: {min(xvals)}..{max(xvals)}   loc Y range: {min(yvals)}..{max(yvals)}")
    print("  per-element (tag | loc x1,y1,x2,y2 | text):")
    for m in elems[:12]:
        tag = m.group(1)
        x1, y1, x2, y2 = (int(v) for v in m.groups()[1:])
        # text right after the 4th loc, up to next tag
        after = doctags[m.end():m.end() + 60].split("<")[0].strip()
        print(f"    {tag:24s} {x1:3d},{y1:3d},{x2:3d},{y2:3d}  | {after[:40]}")

    # Fitted per-axis grid (the promising approach): x_px = loc_x/grid_x * W, etc.
    im = img.copy()
    d = ImageDraw.Draw(im)
    seen = set()
    for m in _BOX_RE.finditer(doctags):
        tag = m.group(1)
        x1, y1, x2, y2 = (int(v) for v in m.groups()[1:])
        key = (x1, y1, x2, y2)
        if key in seen:          # collapsed list_item boxes → draw once
            continue
        seen.add(key)
        box = [x1 / args.grid_x * W, y1 / args.grid_y * H,
               x2 / args.grid_x * W, y2 / args.grid_y * H]
        d.rectangle(box, outline=_color(tag), width=3)
    out = f"box_fitted_gx{int(args.grid_x)}_gy{int(args.grid_y)}.png"
    im.save(out)
    print(f"  saved {out}  (grid_x={args.grid_x}, grid_y={args.grid_y})")

if __name__ == "__main__":
    main()
