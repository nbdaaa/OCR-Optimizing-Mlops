"""
Calibrate the DocTags loc → pixel mapping using a GROUND-TRUTH training sample.

The training labels' <loc> coords were generated by docling's formula
(loc = 500 * coord / page_dim) relative to the image stored in the parquet, so
per-axis mapping (coord = loc/500 * W) SHOULD reproduce the boxes exactly. Render
all 3 schemes on a real sample → whichever aligns is the correct one.

Usage:
    python calibrate_boxes.py --row 0
Env/flags: HF_TOKEN (for the private dataset), --repo, --file (parquet shard).
Outputs: box_<scheme>.png for each scheme + prints image size and loc ranges.
"""
from __future__ import annotations

import argparse
import io
import os
import re

import pandas as pd
from PIL import Image, ImageDraw

_BOX_RE = re.compile(r"<([a-z_0-9]+)><loc_(\d+)><loc_(\d+)><loc_(\d+)><loc_(\d+)>")
_COLORS = {"section_header": (220, 40, 40), "title": (220, 40, 40),
           "text": (40, 110, 215), "list_item": (40, 160, 60),
           "caption": (210, 130, 20), "picture": (160, 40, 200),
           "table": (20, 170, 170), "page_footer": (130, 130, 130),
           "page_header": (130, 130, 130)}

def _color(tag):
    for k, c in _COLORS.items():
        if tag.startswith(k):
            return c
    return (90, 90, 90)

def _decode(field):
    b = field.get("bytes") if isinstance(field, dict) else field
    return Image.open(io.BytesIO(b)).convert("RGB")

def _map(lx, ly, W, H, scheme):
    if scheme == "per-axis":
        return lx / 500 * W, ly / 500 * H
    S = max(W, H)
    if scheme == "square-topleft":
        return lx / 500 * S, ly / 500 * S
    return lx / 500 * S - (S - W) / 2, ly / 500 * S - (S - H) / 2

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", default="nbdaaa/all-ocr-data")
    ap.add_argument("--file", default="data/train-00000-of-00064.parquet")
    ap.add_argument("--row", type=int, default=0)
    args = ap.parse_args()

    from huggingface_hub import hf_hub_download
    p = hf_hub_download(args.repo, args.file, repo_type="dataset",
                        token=os.environ.get("HF_TOKEN"))
    df = pd.read_parquet(p)
    row = df.iloc[args.row]
    img = _decode(row["image"])
    doctags = row["output_text"]
    W, H = img.size

    xs = [int(v) for m in _BOX_RE.finditer(doctags) for v in m.groups()[1:]]
    print(f"image {W}x{H}px · loc count {len(list(_BOX_RE.finditer(doctags)))} · "
          f"loc range x/y min={min(xs) if xs else '-'} max={max(xs) if xs else '-'}")

    for scheme in ("per-axis", "square-topleft", "square-centered"):
        im = img.copy()
        d = ImageDraw.Draw(im)
        for m in _BOX_RE.finditer(doctags):
            tag = m.group(1)
            x1, y1, x2, y2 = (int(v) for v in m.groups()[1:])
            ax, ay = _map(x1, y1, W, H, scheme)
            bx, by = _map(x2, y2, W, H, scheme)
            d.rectangle([ax, ay, bx, by], outline=_color(tag), width=3)
        out = f"box_{scheme}.png"
        im.save(out)
        print(f"  saved {out}")

if __name__ == "__main__":
    main()
